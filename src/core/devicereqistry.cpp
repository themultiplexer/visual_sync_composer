std::vector<std::array<uint8_t, 6>> devicereqistry::macs() {
    std::vector<std::tuple<std::array<uint8_t, 6>, uint8_t>> data;
    data = devices();
    std::vector<std::array<uint8_t, 6>> result;
    result.reserve(data.size());

    for (const auto& item : data) {
        result.push_back(std::get<0>(item));
    }
    return result;
}